"""
V2X-Real Dataset for Same-Vehicle Point Cloud Registration
============================================================
"""

import logging
from pathlib import Path
from typing import Dict, List, Tuple

import torch
from torch.utils.data import Dataset

from utils.helpers import x1_to_x2

from .v2x_real import _SPLIT_DIRNAMES, load_yaml, read_point_cloud

# A pair entry: ((agent_dir, prev_timestamp), (agent_dir, curr_timestamp), is_first_frame)
SameVehiclePairEntry = Tuple[Tuple[Path, str], Tuple[Path, str], bool]

logger = logging.getLogger(__name__)


def build_same_vehicle_pairs(root_dir: str) -> List[SameVehiclePairEntry]:
    """
    Build consecutive-frame pairs for each vehicle agent.

    Parameters
    ----------
    root_dir : str
        Path to a dataset split folder (e.g. ``V2X-Real-Lidar-64/train``),
        containing one subfolder per scenario, each holding one subfolder
        per agent named after the agent id (negative for infrastructure,
        non-negative for vehicles).

    Returns
    -------
    list of ((Path, str), (Path, str), bool)
        One entry per consecutive pair of frames of the same vehicle
        agent: ``((agent_dir, prev_timestamp), (agent_dir, curr_timestamp),
        is_first_frame)``, where ``is_first_frame`` is True for the first
        pair of each agent's sequence. Infrastructure agents (negative
        ids) are excluded. Pairs are ordered scenario by scenario, then
        by agent folder, then by ascending timestamp.
    """
    pairs: List[SameVehiclePairEntry] = []

    for scenario_dir in sorted(Path(root_dir).iterdir()):
        if not scenario_dir.is_dir():
            continue

        vehicle_dirs = []
        for agent_dir in sorted(scenario_dir.iterdir()):
            if not agent_dir.is_dir():
                continue
            try:
                agent_id = int(agent_dir.name)
            except ValueError:
                continue
            if agent_id >= 0:
                vehicle_dirs.append(agent_dir)

        for vehicle_dir in vehicle_dirs:
            timestamps = sorted(p.stem for p in vehicle_dir.glob("*.yaml"))
            for i in range(1, len(timestamps)):
                pairs.append(
                    (
                        (vehicle_dir, timestamps[i - 1]),
                        (vehicle_dir, timestamps[i]),
                        i == 1,
                    )
                )

    return pairs


class V2XRealSameVehicle(Dataset):
    """
    PyTorch Dataset for same-vehicle point cloud registration on V2X-Real.

    Each sample pairs a vehicle's previous LiDAR frame with its current
    one, so registering them aligns the point clouds generated by that
    same car over time.

    Parameters
    ----------
    root_dir : str
        Path to the dataset root (e.g. ``v2xreal``), containing the
        ``train``, ``val`` and ``test`` split folders.
    split : str, default "all"
        Which split to load: ``"train"``, ``"val"``, ``"test"`` or
        ``"all"``. ``"all"`` concatenates pairs from all three splits,
        in ``train``, ``val``, ``test`` order.
    """

    def __init__(
        self,
        root_dir: str,
        split: str = "all",
    ) -> None:
        if split not in ("all", *_SPLIT_DIRNAMES):
            raise ValueError(
                f"Invalid split '{split}', expected one of "
                f"{('all', *_SPLIT_DIRNAMES)}"
            )

        root_dir = Path(root_dir)
        if not root_dir.exists():
            raise FileNotFoundError(f"Directory not found: {root_dir}")
        if not root_dir.is_dir():
            raise NotADirectoryError(f"Not a directory: {root_dir}")

        self.root_dir = root_dir
        self.split = split

        split_dirnames = _SPLIT_DIRNAMES if split == "all" else (split,)
        self.pairs: List[SameVehiclePairEntry] = []
        for split_dirname in split_dirnames:
            split_dir = self.root_dir / split_dirname
            if not split_dir.exists():
                raise FileNotFoundError(f"Directory not found: {split_dir}")
            if not split_dir.is_dir():
                raise NotADirectoryError(f"Not a directory: {split_dir}")
            self.pairs.extend(build_same_vehicle_pairs(split_dir))

    def __getitem__(self, idx: int) -> Dict:
        """
        Load a registration sample.

        Parameters
        ----------
        idx : int
            Index into ``self.pairs``.

        Returns
        -------
        dict
            ``infra_pts`` / ``vehicle_pts`` : (N, 3) float32 tensors with
            the previous and current raw point clouds, respectively
            (named to match the `ExperimentPipeline` schema).
            ``T_vehicle_to_infra`` / ``T_infra_to_vehicle`` : (4, 4)
            float32 tensors with the rigid transforms between the
            current and previous LiDAR frames. ``meta`` : dict with
            scenario, agent id, timestamps and an ``is_first_frame``
            flag.
        """
        (prev_dir, prev_ts), (curr_dir, curr_ts), is_first_frame = self.pairs[idx]

        prev_pts = read_point_cloud(prev_dir / f"{prev_ts}.bin")
        curr_pts = read_point_cloud(curr_dir / f"{curr_ts}.bin")

        prev_yaml = load_yaml(prev_dir / f"{prev_ts}.yaml")
        curr_yaml = load_yaml(curr_dir / f"{curr_ts}.yaml")

        prev_imu_pose = prev_yaml["lidar_pose"]
        curr_imu_pose = curr_yaml["lidar_pose"]
        prev_true_pose = prev_yaml["true_ego_pose"]
        curr_true_pose = curr_yaml["true_ego_pose"]

        # x1_to_x2 maps points from x1's local frame into x2's local frame
        T_curr_to_prev_imu = x1_to_x2(curr_imu_pose, prev_imu_pose)
        T_prev_to_curr_imu = x1_to_x2(prev_imu_pose, curr_imu_pose)
        T_curr_to_prev = x1_to_x2(curr_true_pose, prev_true_pose)
        T_prev_to_curr = x1_to_x2(prev_true_pose, curr_true_pose)

        return {
            "infra_pts": torch.from_numpy(prev_pts),
            "vehicle_pts": torch.from_numpy(curr_pts),
            "T_vehicle_to_infra": torch.from_numpy(T_curr_to_prev).float(),
            "T_infra_to_vehicle": torch.from_numpy(T_prev_to_curr).float(),
            "T_vehicle_to_infra_imu": torch.from_numpy(T_curr_to_prev_imu).float(),
            "T_infra_to_vehicle_imu": torch.from_numpy(T_prev_to_curr_imu).float(),
            "meta": {
                "scenario": prev_dir.parent.name,
                "agent": prev_dir.name,
                "prev_timestamp": prev_ts,
                "curr_timestamp": curr_ts,
                "is_first_frame": is_first_frame,
            },
        }

    def __len__(self):
        return len(self.pairs)